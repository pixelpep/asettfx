local crc32 = require("asettfx.crc32")
local png_meta = require("asettfx.png_meta")
local meta = require("asettfx.meta")

return function(T)
  local fixtures = T.root .. "/tests/fixtures/"
  local function load(name) return png_meta.load(fixtures .. name) end

  T.test("crc32 known value", function()
    T.eq(crc32.crc32("123456789"), 0xCBF43926)
    T.eq(crc32.crc32("xx123456789yy", 3, 11), 0xCBF43926)
  end)

  T.test("variable template: metadata is read and valid", function()
    local r = load("template-var.png")
    T.eq(r.status, "ok")
    T.eq(r.meta.mode, "var")
    T.eq(r.meta.cell.w, 8)
    T.eq(r.meta.grid.rows, 3 * 2)
    T.eq(r.meta.guide.prefill, true)
    T.eq(r.size.width, 128)
    T.eq(r.size.height, 48)
    T.eq(#meta.validate(r.meta, r.size), 0)
  end)

  T.test("monospace template", function()
    local r = load("template-mono.png")
    T.eq(r.status, "ok")
    T.eq(r.meta.mode, "mono")
    T.eq(r.meta.widthSource, nil)
  end)

  T.test("PNG without metadata is absent", function()
    local r = load("template-no-meta.png")
    T.eq(r.status, "absent")
    T.eq(r.size.width, 128)
  end)

  T.test("bad JSON is invalid", function()
    local r = load("template-bad-json.png")
    T.eq(r.status, "invalid")
    T.truthy(r.reason:find("JSON"), r.reason)
  end)

  T.test("unsupported version is invalid", function()
    local r = load("template-bad-schema.png")
    T.eq(r.status, "invalid")
    T.truthy(r.reason:find("version"), r.reason)
  end)

  T.test("damaged chunk is a checksum error", function()
    local bytes = T.read(fixtures .. "template-corrupt-crc.png")
    T.eq(png_meta.parse(bytes, "asettfx").status, "crc-error")
    local r = load("template-corrupt-crc.png")
    T.eq(r.status, "invalid")
    T.truthy(r.reason:find("checksum"), r.reason)
  end)

  T.test("a resized canvas keeps valid settings", function()
    local r = load("template-wrong-size.png")
    T.eq(r.status, "ok")
    T.eq(r.size.height, 56)
    T.eq(#meta.validate(r.meta, r.size), 1)
  end)

  T.test("truncated and non-PNG files", function()
    local bytes = T.read(fixtures .. "template-var.png")
    T.eq(png_meta.parse(bytes:sub(1, 40), "asettfx").status, "truncated")
    T.eq(png_meta.parse("not a png at all", "asettfx").status, "not-png")
    T.eq(png_meta.interpret(png_meta.parse("not a png at all", "asettfx")).status, "absent")
    T.eq(png_meta.load(fixtures .. "does-not-exist.png").status, "absent")
  end)

  T.test("metadata after the first IDAT is not read", function()
    local bytes = T.read(fixtures .. "template-var.png")
    local text_at = bytes:find("tEXt", 1, true)
    local len = string.unpack(">I4", bytes, text_at - 4)
    local chunk = bytes:sub(text_at - 4, text_at + 7 + len)
    local without = bytes:sub(1, text_at - 5) .. bytes:sub(text_at + 8 + len)
    local moved = without:sub(1, #without - 12) .. chunk .. without:sub(#without - 11)
    T.eq(#moved, #bytes)
    T.eq(png_meta.parse(moved, "asettfx").status, "absent")
  end)
end
