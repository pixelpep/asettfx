// Generates aseprite-extension/digiface/blank.lua: the code point ranges of space, control and format characters
// (Unicode Zs, Cc, Cf), the same set as web/src/template.js, so the web tool and the extension agree.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

export function ranges() {
  const re = /^[\p{Cc}\p{Zs}\p{Cf}]$/u;
  const out = [];
  let start = -1;
  for (let cp = 0; cp <= 0x110000; cp++) {
    const hit = cp <= 0x10FFFF && !(cp >= 0xD800 && cp <= 0xDFFF) && re.test(String.fromCodePoint(cp));
    if (hit && start < 0) start = cp;
    if (!hit && start >= 0) { out.push([start, cp - 1]); start = -1; }
  }
  return out;
}

export function render() {
  const rows = ranges().map(([a, b]) => `  { 0x${a.toString(16).toUpperCase()}, 0x${b.toString(16).toUpperCase()} },`).join('\n');
  return `-- Generated by tools/gen-blank.mjs. Do not edit.
-- Code point ranges of space, control and format characters (Unicode Zs, Cc, Cf).
local RANGES = {
${rows}
}

local M = {}

function M.is_blank(cp)
  for _, r in ipairs(RANGES) do
    if cp < r[1] then return false end
    if cp <= r[2] then return true end
  end
  return false
end

return M
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..');
  writeFileSync(join(root, 'aseprite-extension', 'digiface', 'blank.lua'), render());
  console.log('aseprite-extension/digiface/blank.lua: ' + ranges().length + ' ranges');
}
