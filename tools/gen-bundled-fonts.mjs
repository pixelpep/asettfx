// Generates, from web/fonts/fonts.json and the original font files in web/fonts/original/:
//   web/src/bundled-fonts.js        the catalog (names, authors, licenses), small, loaded with the page;
//   web/fonts/data/<id>.js          the font itself as base64, one file per font, loaded when the font is chosen
//                                   (the page works from file://, where a font file cannot be fetched).
// The font files are included unchanged.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'web', 'fonts');

export function build() {
  const catalog = JSON.parse(readFileSync(join(dir, 'fonts.json'), 'utf8'));
  const data = {};
  for (const f of catalog) {
    const base64 = readFileSync(join(dir, 'original', f.file)).toString('base64');
    const notice = f.copyright ? `// ${f.copyright}\n// This Font Software is licensed under the ${{ 'SIL OFL 1.1': 'SIL Open Font License, Version 1.1', MIT: 'MIT License' }[f.license] || f.license}; the license text is in web/fonts/${f.licenseText}.\n` : '';
    data[f.id] = `// Generated by tools/gen-bundled-fonts.mjs from web/fonts/original/${f.file}, unchanged. ${f.label} by ${f.author}, ${f.license}: see web/fonts/LICENSES.md.
${notice}
(function (root) {
  root.ASETTFX = root.ASETTFX || {};
  (root.ASETTFX.fontData = root.ASETTFX.fontData || {})[${JSON.stringify(f.id)}] = '${base64}';
})(typeof self !== 'undefined' ? self : this);
`;
  }
  const entries = catalog.map(({ id, label, author, license, licenseUrl, source, copyright }) => ({ id, label, author, license, licenseUrl, source, ...(copyright ? { copyright } : {}) }));
  const catalogJs = `// Generated by tools/gen-bundled-fonts.mjs from web/fonts/fonts.json. Do not edit.
// Pixel fonts shipped with the template generator. Credits and license links: web/fonts/LICENSES.md.
(function (root, factory) {
  const api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  else { root.ASETTFX = root.ASETTFX || {}; root.ASETTFX.bundledFonts = api; }
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';
  return { fonts: ${JSON.stringify(entries, null, 2).replace(/\n/g, '\n  ')} };
});
`;
  return { catalogJs, data, catalog };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { catalogJs, data, catalog } = build();
  writeFileSync(join(root, 'web', 'src', 'bundled-fonts.js'), catalogJs);
  for (const f of catalog) writeFileSync(join(dir, 'data', f.id + '.js'), data[f.id]);
  console.log(catalog.length + ' bundled fonts written (web/src/bundled-fonts.js and web/fonts/data/*.js)');
}
